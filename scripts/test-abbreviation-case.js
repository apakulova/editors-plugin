const assert = require("assert");
const fs = require("fs");
const path = require("path");
const vm = require("vm");

const NBSP = "\u00A0";
const root = path.resolve(__dirname, "..");
const compiled = fs.readFileSync(path.join(root, "dist/code.js"), "utf8");
assert(compiled.includes("void run();"), "Не найден безопасный вход для изолированных проверок");
const runtime = { console, clearTimeout, setTimeout, performance: { now: () => 0 }, globalThis: { performance: { now: () => 0 } } };
vm.createContext(runtime);
vm.runInContext(compiled.replace("void run();", "globalThis.clean = cleanTypographyWithMetadata; globalThis.buildNumberLayerContexts = buildNumberLayerContexts;"), runtime);
const clean = runtime.globalThis.clean;
const buildNumberLayerContexts = runtime.globalThis.buildNumberLayerContexts;
assert.strictEqual(typeof clean, "function");
assert.strictEqual(typeof buildNumberLayerContexts, "function");

const failures = [];
let checks = 0;
const visible = (text) => text.replaceAll(NBSP, "⍽").replaceAll("\n", "\\n");
const options = (mode) => ({ mode, processHiddenNodes: false, processLockedNodes: false, recolorExistingAsterisks: false });
const wholeLayerStyle = (textCase) => (text) => ({ originalText: text, segments: [{ start: 0, end: text.length, textCase }] });
const contextFor = (factory, text) => factory === null ? null : factory(text);

function equal(name, actual, expected) {
  checks += 1;
  if (actual !== expected) failures.push(`${name}\n  ожидалось: ${visible(expected)}\n  получено:  ${visible(actual)}`);
}

function run(text, mode, indexes, caseContextFactory, numberLayerContext = null) {
  return clean(text, options(mode), indexes, null, numberLayerContext, null, contextFor(caseContextFactory, text));
}

function check(name, input, expected, caseContextFactory = null, numberContextFactory = null) {
  for (const mode of ["beauty", "development"]) {
    const expectedText = mode === "beauty" ? expected : expected.replaceAll(NBSP, "*");
    let current = input;
    let indexes = [];
    for (let pass = 1; pass <= 3; pass += 1) {
      const result = run(current, mode, indexes, caseContextFactory, numberContextFactory === null ? null : numberContextFactory(current));
      equal(`${name}, ${mode}, запуск ${pass}`, result.text, expectedText);
      current = result.text;
      indexes = result.developmentMarkerIndexes;
    }
  }
}

