function checkLettersAndPeriods(name, input) {
  for (const mode of ["beauty", "development"]) {
    let current = input;
    let indexes = [];
    const expectedLetters = input.match(/[A-Za-zА-Яа-яЁё]/g)?.join("") ?? "";
    const expectedPeriods = input.match(/\./g)?.length ?? 0;
    let first = null;
    for (let pass = 1; pass <= 3; pass += 1) {
      const result = run(current, mode, indexes, null);
      equal(`${name}, ${mode}, буквы, запуск ${pass}`, result.text.match(/[A-Za-zА-Яа-яЁё]/g)?.join("") ?? "", expectedLetters);
      equal(`${name}, ${mode}, точки, запуск ${pass}`, String(result.text.match(/\./g)?.length ?? 0), String(expectedPeriods));
      if (first !== null) equal(`${name}, ${mode}, повтор ${pass}`, result.text, first);
      first = result.text;
      current = result.text;
      indexes = result.developmentMarkerIndexes;
    }
  }
}
