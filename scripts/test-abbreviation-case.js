function contextNodes(texts) {
  const nodes = texts.map((characters, index) => ({
    characters, id: `piece-context-${index}`, layoutPositioning: "AUTO", locked: false,
    maxLines: null, parent: null, removed: false, rotation: 0,
    textAutoResize: "WIDTH_AND_HEIGHT", textTruncation: "DISABLED", type: "TEXT", visible: true,
  }));
  const parent = { children: nodes, id: "piece-context-parent", layoutMode: "HORIZONTAL", layoutWrap: "NO_WRAP", locked: false, parent: null, type: "FRAME", visible: true };
  nodes.forEach((node) => { node.parent = parent; });
  return nodes;
}

